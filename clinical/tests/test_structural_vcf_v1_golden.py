"""
PARSER RULE SET `structural_vcf/1` IS FROZEN BY THESE FILES.

A stored call set records the rule set that produced its derived document and is re-verified against it for as long
as it exists: at validation, and (fail-closed) every time the clinical map draws it. If the behaviour of the function
registered as "structural_vcf/1" changes AT ALL, every stored version-1 document stops verifying and the map hides all
of that evidence. The registry guard (`test_genome_structural_storage.py`) only proves the rule set reproduces what it
writes TODAY, which an edit satisfies automatically; this file proves it reproduces what it wrote BEFORE.

`golden/structural_vcf_v1/` holds two VCFs covering every record shape, every status and every warning the parser can
emit, and the exact document version 1 produced for each. They were generated once from the rule set as it stands and
reviewed by hand. They are not regenerated by any test. To change parsing semantics, add `structural_vcf/2` with its own
function and golden files and keep this one; do not touch these files.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re

import pytest

from clinical.genome_analysis import (
    CALLSET_PARSER_VERSION,
    PARSER_RULESETS,
    callset_from_document,
    verify_document_for_version,
)
from clinical.genome_analysis import structural_vcf as parser_module

GOLDEN = pathlib.Path(__file__).resolve().parent / "golden" / "structural_vcf_v1"
CASES = {"sv_all_kinds": "sv", "cnv_all_kinds": "cnv"}
# SHA-256 of each frozen file (line endings normalised to LF, as the migration checksums are)
PINS = {
    "sv_all_kinds.vcf": "6a3992ec7c28f7b875e839c2067f99be620f14b35842623ae64010808eb12ae8",
    "sv_all_kinds.expected.json": "d363634bf6ef1eda5480d64029a04916b5101b885f5b7d1ba4104d0211bd9090",
    "cnv_all_kinds.vcf": "2546a8864a99f2f27a7654184bfddb65909f75ce58fda988d4473a04ad5d4b72",
    "cnv_all_kinds.expected.json": "cbfa1dae7505e052e3938ef5ebce7776a150148abfeeb8c4c2288e82806d2cb8",
}


def _bytes(name: str) -> bytes:
    return (GOLDEN / name).read_bytes().replace(b"\r\n", b"\n")


def _expected(case: str) -> dict:
    return json.loads(_bytes(f"{case}.expected.json").decode("utf-8"))


class TestTheFixturesAreTheFrozenOnes:
    @pytest.mark.parametrize("name", sorted(PINS))
    def test_each_file_is_byte_for_byte_the_reviewed_one(self, name):
        assert hashlib.sha256(_bytes(name)).hexdigest() == PINS[name], (
            f"{name} changed. These files freeze parser version 1; add a new rule set instead of editing them."
        )

    def test_the_current_version_is_the_one_they_freeze(self):
        assert CALLSET_PARSER_VERSION == "structural_vcf/1" or CALLSET_PARSER_VERSION in PARSER_RULESETS
        assert "structural_vcf/1" in PARSER_RULESETS


class TestVersionOneStillReproducesWhatItWrote:
    @pytest.mark.parametrize("case", sorted(CASES))
    def test_the_document_is_reproduced_exactly(self, case):
        text = _bytes(f"{case}.vcf").decode("utf-8")
        again = PARSER_RULESETS["structural_vcf/1"](text, assembly="GRCh38", record_class=CASES[case]).to_document()
        assert json.loads(json.dumps(again)) == _expected(case)

    @pytest.mark.parametrize("case", sorted(CASES))
    def test_the_stored_document_still_verifies_and_still_rehydrates(self, case):
        text = _bytes(f"{case}.vcf").decode("utf-8")
        doc = _expected(case)
        assert verify_document_for_version("structural_vcf/1", text, doc) is True
        rebuilt = callset_from_document(doc, caller="Golden 1.0", call_set_id="golden")
        assert rebuilt.counts() == doc["counts"]

    @pytest.mark.parametrize("case", sorted(CASES))
    def test_one_changed_character_in_the_document_or_the_bytes_is_detected(self, case):
        text = _bytes(f"{case}.vcf").decode("utf-8")
        doc = _expected(case)
        doc["records"][0]["status"] = "uncertain" if doc["records"][0]["status"] != "uncertain" else "detected"
        assert verify_document_for_version("structural_vcf/1", text, doc) is False
        assert (
            verify_document_for_version("structural_vcf/1", text.replace("\t60", "\t61", 1), _expected(case)) is False
        )


class TestTheFixturesCoverTheWholeRuleSet:
    def test_every_warning_the_parser_can_emit_appears_in_a_golden_document(self):
        """If someone adds a warning, this fails until a golden record exercises it (and the pins are re-reviewed)."""
        source = pathlib.Path(parser_module.__file__).read_text(encoding="utf-8")
        literals = re.findall(r'warnings\.append\(f?"([^"]+)"', source)
        assert literals, "the scan found no warnings at all: it would be vacuous"
        golden_text = "".join(_bytes(f"{case}.expected.json").decode("utf-8") for case in CASES)
        missing = [lit for lit in literals if lit.split("{")[0] not in golden_text]
        assert not missing, f"warnings no golden record exercises: {missing}"

    @pytest.mark.parametrize("case", sorted(CASES))
    def test_every_status_and_a_record_for_each_shape_is_present(self, case):
        records = _expected(case)["records"]
        assert {r["status"] for r in records} == {"detected", "uncertain", "unsupported", "invalid"}
        assert all(r["reason"] for r in records if r["status"] in ("invalid", "unsupported")), (
            "every refusal keeps its why"
        )

    def test_the_sv_shapes_are_all_there(self):
        records = [r["record"] for r in _expected("sv_all_kinds")["records"] if r["record"]]
        assert {r["sv_type"] for r in records} >= {"DEL", "DUP", "INV", "INS", "BND"}
        assert {r["partner_status"] for r in records if r["sv_type"] == "BND"} >= {
            "partner_given",
            "single_breakend",
            "partner_not_specified",
            "partner_on_unplaced_contig",
        }
        assert {b["precision"] for r in records for b in r["breakpoints"]} == {
            "precise",
            "interval",
            "imprecise_unquantified",
        }

    def test_the_cnv_shapes_are_all_there(self):
        records = [r["record"] for r in _expected("cnv_all_kinds")["records"] if r["record"]]
        assert {r["cnv_type"] for r in records} >= {"deletion", "duplication", "copy_number_change"}
        assert {r["copy_number_source"] for r in records} >= {"INFO:CN", "ALT"}
        assert any(r["log2_ratio"] is not None for r in records) and any(r["quality"] == 1.5e22 for r in records)
